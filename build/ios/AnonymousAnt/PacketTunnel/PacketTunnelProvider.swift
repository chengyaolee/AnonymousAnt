import NetworkExtension
import AntTunnel // Generated by gomobile bind

class PacketTunnelProvider: NEPacketTunnelProvider, MobilePacketFlowProtocol {
    
    private var isTunnelActive = false

    override func startTunnel(options: [String : NSObject]?, completionHandler: @escaping (Error?) -> Void) {
        guard let conf = (self.protocolConfiguration as? NETunnelProviderProtocol)?.providerConfiguration else {
            completionHandler(NSError(domain: "AnonymousAnt", code: 1, userInfo: [NSLocalizedDescriptionKey: "Missing configuration"]))
            return
        }

        let serverAddr = conf["server_addr"] as? String ?? "127.0.0.1:8443"
        let serverKey = conf["server_key"] as? String ?? ""
        let transport = conf["transport"] as? String ?? "tls"
        let sni = conf["sni"] as? String ?? "gateway.internal"

        // Configure iOS Virtual IP & Default Route
        let settings = NEPacketTunnelNetworkSettings(tunnelRemoteAddress: "10.8.0.1")
        
        let ipv4Settings = NEIPv4Settings(addresses: ["10.8.0.2"], subnetMasks: ["255.255.255.0"])
        ipv4Settings.includedRoutes = [NEIPv4Route.default()]
        settings.ipv4Settings = ipv4Settings

        // Enforce DNS to prevent DNS leaks
        let dnsSettings = NEDNSSettings(servers: ["1.1.1.1", "1.0.0.1"])
        dnsSettings.matchDomains = [""]
        settings.dnsSettings = dnsSettings

        // Set tunnel MTU to 1420
        settings.tunnelOverheadBytes = NSNumber(value: 80)

        self.setTunnelNetworkSettings(settings) { [weak self] error in
            if let error = error {
                completionHandler(error)
                return
            }

            guard let self = self else { return }

            // Initialize the embedded Go engine
            var startErr: NSError?
            MobileStartTunnel(serverAddr, serverKey, transport, sni, self, &startErr)

            if let startErr = startErr {
                completionHandler(startErr)
                return
            }

            self.isTunnelActive = true
            self.startPacketReadLoop()
            completionHandler(nil)
        }
    }

    // Packet read loop: iOS IP stack -> Go Engine -> Encrypted Network Socket
    private func startPacketReadLoop() {
        guard isTunnelActive else { return }

        packetFlow.readPackets { [weak self] (packets, protocols) in
            guard let self = self, self.isTunnelActive else { return }

            for packet in packets {
                MobileOnPacketFromDevice(packet)
            }

            self.startPacketReadLoop()
        }
    }

    // Callback from Go Engine: Decrypted Network Packet -> iOS IP stack
    func writePacket(_ pkt: Data?) {
        guard let pkt = pkt, isTunnelActive else { return }
        packetFlow.writePackets([pkt], withProtocols: [NSNumber(value: AF_INET)])
    }

    override func stopTunnel(with reason: NEProviderStopReason, completionHandler: @escaping () -> Void) {
        isTunnelActive = false
        MobileStopTunnel()
        completionHandler()
    }

    override func handleAppMessage(_ messageData: Data, completionHandler: ((Data?) -> Void)?) {
        let statsJson = MobileGetStats()
        completionHandler?(statsJson.data(using: .utf8))
    }
}
